def test_successful_run_writes_only_under_run_dir(tmp_path, monkeypatch):
    monkeypatch.setenv("HERMES_HOME", str(tmp_path / "hermes-home"))
    nightly = import_nightly()
    runner = FakeRunner()

    summary = nightly.run_nightly(
        repo_root=REPO_ROOT,
        run_id="unit-success",
        command_runner=runner,
        timeout_seconds=10,
    )

    run_dir = tmp_path / "hermes-home" / "foundry" / "runs" / "unit-success"
    assert summary["ok"] is True
    assert summary["status"] == "passed"
    assert (run_dir / "summary.json").exists()
    assert (run_dir / "metadata" / "git.json").exists()
    assert (run_dir / "reliability" / "result.json").exists()
    assert len(sorted((run_dir / "candidates").rglob("*.json"))) == 3
    assert (run_dir / "routing_smoke" / "results.json").exists()
    assert not (tmp_path / "hermes-home" / "foundry" / "candidates").exists()
    assert not (tmp_path / "hermes-home" / "memories").exists()
    assert not (tmp_path / "hermes-home" / "skills").exists()
    assert not (tmp_path / "hermes-home" / "config.yaml").exists()
    assert not (tmp_path / "hermes-home" / "cron").exists()


