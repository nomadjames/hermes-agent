def test_cli_without_run_id_uses_safe_default_and_writes_run_artifacts(tmp_path, monkeypatch):
    home = tmp_path / "hermes-home"
    monkeypatch.setenv("HERMES_HOME", str(home))

    result = subprocess.run(
        [sys.executable, str(SCRIPT_PATH), "--repo-root", str(REPO_ROOT), "--allow-dirty", "--timeout-seconds", "60"],
        cwd=REPO_ROOT,
        text=True,
        capture_output=True,
        check=False,
    )

    assert result.returncode == 0, result.stderr
    run_root = home / "foundry" / "runs"
    runs = list(run_root.iterdir())
    assert len(runs) == 1
    assert runs[0].name == runs[0].name.lower()
    assert (runs[0] / "summary.json").exists()
