class FakeRunner:
    def __init__(
        self,
        *,
        fail_step=None,
        timeout_step=None,
        stderr="",
        stdout="",
        candidate_symlink_step=None,
        symlink_run_id=None,
    ):
        self.calls = []
        self.fail_step = fail_step
        self.timeout_step = timeout_step
        self.stderr = stderr
        self.stdout = stdout
        self.candidate_symlink_step = candidate_symlink_step
        self.symlink_run_id = symlink_run_id

    def __call__(self, cmd, *, cwd=None, timeout=None, text=True, capture_output=True, check=False, env=None):
        cmd = [str(part) for part in cmd]
        self.calls.append(cmd)
        step = self._step_name(cmd)
        if self.timeout_step == step:
            raise subprocess.TimeoutExpired(cmd=cmd, timeout=timeout, output="partial", stderr="timeout")
        if self.fail_step == step:
            return subprocess.CompletedProcess(cmd, 1, stdout=self.stdout, stderr=self.stderr)
        if cmd[:2] == ["git", "--no-optional-locks"]:
            return self._git_result(cmd)
        if step == "reliability":
            return subprocess.CompletedProcess(cmd, 0, stdout=json.dumps({"ok": True, "cases": []}), stderr="")
        if step in {"self_audit", "skill_candidates", "routing_bench"}:
            candidate_json = self._candidate_json(cmd, step, env=env)
            return subprocess.CompletedProcess(cmd, 0, stdout=candidate_json, stderr="")
        raise AssertionError(f"unexpected command: {cmd}")

    def _step_name(self, cmd):
        if "agent.clarence_reliability.runner" in cmd:
            return "reliability"
        joined = " ".join(cmd)
        if "foundry_self_audit.py" in joined:
            return "self_audit"
        if "foundry_skill_candidates.py" in joined:
            return "skill_candidates"
        if "foundry_routing_bench.py" in joined:
            return "routing_bench"
        if cmd[:2] == ["git", "--no-optional-locks"]:
            return "git"
        return "unknown"

    def _git_result(self, cmd):
        if "rev-parse" in cmd and "--abbrev-ref" in cmd:
            return subprocess.CompletedProcess(cmd, 0, stdout="clarence/foundry-phase3-nightly-runner\n", stderr="")
        if "rev-parse" in cmd and "HEAD" in cmd:
            return subprocess.CompletedProcess(cmd, 0, stdout="abc123\n", stderr="")
        if "status" in cmd:
            return subprocess.CompletedProcess(cmd, 0, stdout="", stderr="")
        if "merge-base" in cmd:
            return subprocess.CompletedProcess(cmd, 0, stdout="base123\n", stderr="")
        return subprocess.CompletedProcess(cmd, 0, stdout="", stderr="")

    def _candidate_json(self, cmd, step, env=None):
        if self.candidate_symlink_step == step:
            assert env is not None
            assert self.symlink_run_id is not None
            candidate_root = Path(env["HERMES_HOME"]) / "foundry" / "runs" / self.symlink_run_id / "candidates"
            escape = candidate_root.parent.parent / f"escaped-{step}"
            escape.mkdir(parents=True, exist_ok=True)
            if candidate_root.exists() and candidate_root.is_dir() and not candidate_root.is_symlink():
                candidate_root.rmdir()
            candidate_root.symlink_to(escape, target_is_directory=True)
        slug = cmd[cmd.index("--slug") + 1]
        kind = {
            "self_audit": "self_audit",
            "skill_candidates": "skill_candidates",
            "routing_bench": "routing_bench",
        }[step]
        candidate = build_candidate_envelope(
            kind=kind,
            title=f"{step} test candidate",
            summary="Generated by unit-test fake runner.",
            source={"script": f"scripts/foundry_{step}.py", "phase": "foundry-phase3-test"},
            payload={"step": step, "network_calls": "none"},
            slug=slug,
        )
        return json.dumps(candidate)


def import_nightly():
    return importlib.import_module("agent.clarence_foundry.nightly")


def test_importing_nightly_does_not_create_foundry(tmp_path, monkeypatch):
    monkeypatch.setenv("HERMES_HOME", str(tmp_path / "hermes-home"))

    import_nightly()

    assert not (tmp_path / "hermes-home" / "foundry").exists()


