def test_generator_commands_print_json_and_wrapper_writes_candidates(tmp_path, monkeypatch):
    monkeypatch.setenv("HERMES_HOME", str(tmp_path / "hermes-home"))
    nightly = import_nightly()
    runner = FakeRunner()

    summary = nightly.run_nightly(repo_root=REPO_ROOT, run_id="unit-generators", command_runner=runner)

    assert summary["ok"] is True
    generator_calls = [
        call
        for call in runner.calls
        if any(
            name in " ".join(call)
            for name in ["foundry_self_audit.py", "foundry_skill_candidates.py", "foundry_routing_bench.py"]
        )
    ]
    assert len(generator_calls) == 3
    run_dir = tmp_path / "hermes-home" / "foundry" / "runs" / "unit-generators"
    assert len(sorted((run_dir / "candidates").rglob("*.json"))) == 3
    for call in generator_calls:
        assert "--print-json" in call
        assert "--out-dir" not in call
        assert "--overwrite" not in call


